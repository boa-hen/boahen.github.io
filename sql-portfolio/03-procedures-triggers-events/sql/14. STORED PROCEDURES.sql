-- Stored Procedures
# It is a way to save your SQL code so that you can reuse it over and over again
# when you save it you can call that stored procedure and it will execute every code you wrote within the stored procedure
# it is very useful for storing complex queries, simplifying repetitive code and enhancing performance

SELECT *
FROM employee_salary
WHERE salary >= 50000;

CREATE PROCEDURE large_salaries()
SELECT *
FROM employee_salary
WHERE salary >= 50000;
# This is how to create a stored procedure, however note that this query is too simple
# Actual stored procedures involve complex queries that may be inconvenient to repeatedly keep typing again and again

CALL large_salaries();

USE parks_and_recreation;
DROP procedure IF EXISTS salaries;
CREATE PROCEDURE salaries()
SELECT *
FROM employee_salary
WHERE salary < 50000;
# USE shows which specific db to use, however it is not compulsory in the case where we have only one db
# so it works whether we bring it or not, just as in the previous query
# 'DROP procedure IF EXISTS' does just as the name suggests; it drops (deletes) an already existing procedure. This is to avoid creating duplicate procedures

DELIMITER $$
CREATE PROCEDURE large_salaries2()
BEGIN
	SELECT *
	FROM employee_salary
	WHERE salary >= 50000;
	SELECT *
	FROM employee_salary
	WHERE salary >= 10000;
END $$
DELIMITER ;
# What we have done is we have changed the delimiter from ';' to '$$' so that instead of SQL treating the two queries we want to include in the stored procedure as separate queries, it will treat everything between the delimiter and the END as one complex query just as we want.
# A delimiter is used to end a query so that SQL can differentiate between separate queries.
# After, we changed the delimiter back to ';'. If we do not do this then we will have to start using '$$' as our delimeter which is might be a bit tedious.

CALL large_salaries2();
# Note that when we call the stored procedure we get two outputs because it contains two queries

