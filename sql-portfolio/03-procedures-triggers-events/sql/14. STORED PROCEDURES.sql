-- Paramters
# they are variables that are passed as an input into a stored procedure and they allow the procedure to accept an input value and place it into your code
# when we say we are passing through a parameter we mean when we are calling it
# Parameters in stored procedures are placeholders for values you supply when you call the procedure. Instead of hardcoding a specific value into your procedure, you leave a parameter in its place and pass in whatever value you need at the time of calling it.
# This makes your procedure reusable — the same logic runs, just with different inputs each time, the same way a function works in programming.

# Lets say we want to pass in a parameter say, employee_id
DELIMITER $$
CREATE PROCEDURE emp_id_data(p_employee_id INT)
BEGIN
	SELECT *
	FROM employee_salary
	WHERE employee_id = p_employee_id
    ;
END $$
DELIMITER ;

CALL emp_id_data(4);

SELECT *
FROM employee_salary
WHERE employee_id = 4;
# This confirms that our stored procedure for showing employee data from the salary table works
